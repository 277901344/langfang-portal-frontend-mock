  format: string; // 资源格式
  source: string; // 数据来源
  hasPersonalInfo: '是' | '否' | '是（已脱敏）'; // 是否涉及个人信息
  securityLevel: '1级（公开）' | '2级（受控）' | '3级（敏感）' | '4级（核心）'; // 安全分级分类
